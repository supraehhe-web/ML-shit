"""Generate reports/arm_c_diagnosis_v2.md from the Phase 1 and Phase 2 artifacts.

Every number is read from a JSON/CSV written by a script; nothing is typed in.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from dm_ahr_vit.paths import REPO_ROOT, artifact_dir  # noqa: E402

LOGS = artifact_dir("logs")
OUT = REPO_ROOT / "reports" / "arm_c_diagnosis_v2.md"


def J(name):
    p = LOGS / name
    return json.loads(p.read_text()) if p.exists() else None


def f(x, d=2):
    return "n/a" if x is None else f"{float(x):.{d}f}"


def main() -> int:
    mse = J("arm_c_v2_noise_mse.json")
    scores = J("arm_c_v2_scores.json")
    warm = J("arm_c_v2_warm_start.json")
    over = J("arm_c_v2_overfit.json")
    sweep = J("arm_c_v2_step_sweep.json")
    resp = J("arm_c_v2_respaced.json")
    repro = J("paper_reproduction.json")
    repro256 = J("paper_reproduction_256.json")
    audit = J("dermahair_sample_audit.json")
    fixed_log = J("dmahr_fixed_train_log.json")
    L: list[str] = []
    A = L.append
    A("# Arm C diagnosis, second pass: undertrained, trained wrongly, or a broken sampler?\n")
    A("Generated by `scripts/27_build_diagnosis_v2.py` from the artifacts named in each section. "
      "Validation synthetic pairs only: no test image, label, mask or metric was read to reach any "
      "conclusion here. Thresholds and rules were pre-registered in `reports/decision_log.md` "
      "(D22, D23, D24) before the corresponding jobs ran.\n")
    A("## Summary\n")
    A("The first diagnosis (D19) concluded \"undertrained\" from an identity test that used the "
      "*released* checkpoint. That test can only show that the inference path works for weights that "
      "work; it cannot detect a defect in our own training. Re-examining the trainer found one, and "
      "the retrained model still fails the validity gate, so the honest state is: **the first "
      "checkpoint was trained wrongly, and the corrected retrain is still not good enough to serve as "
      "a confirmatory DM-AHR arm.**\n")
    A("| Question | Answer | Evidence |")
    A("|---|---|---|")
    A("| Was the first trainer faithful to upstream? | **No.** It fed the denoiser `t/T`; upstream "
      "trains and samples with the continuous level sqrt(alpha_bar). | `src/dm_ahr_vit/diffusion/conditioning.py`, "
      "`tests/test_diffusion_conditioning.py` |")
    A("| Was there an EMA or sampling-weights bug? | **No.** Upstream marks `ema_scheduler` \"not used "
      "now\" and no EMA code exists in any upstream Python file, so no EMA weights exist to load. | "
      "`artifacts/logs/dermahair_sample_audit.json` |")
    A("| Did the corrected retrain fix it? | **No.** It improves PSNR from 13.9 to 17.2 dB but stays "
      "below the pre-registered gate of hairy + 3 dB (25.3 dB). | `arm_c_v2_scores.json` |")
    A("| Is the short sampler sound? | **No, not as first written.** Re-deriving a linear schedule over "
      "a shorter chain ends at a different final noise level. A respaced sampler fixes that. | "
      "`tests/test_respacing.py`, `arm_c_v2_respaced.json` |")
    A("| Can the released checkpoint serve as a DM-AHR arm? | **Yes, as an exploratory arm.** It passes "
      "the validity gate at 25 respaced steps. | `arm_c_v2_respaced.json` |")
    A("")
    A("## 1. Static audit of the trainer against upstream\n")
    A("| Item | Upstream | This repository, first version | This repository, now |")
    A("|---|---|---|---|")
    A("| Denoiser conditioning | continuous sqrt(alpha_bar), drawn uniformly in [prev[t-1], prev[t]] | "
      "`t / T` (a value rising 0 to 1 while the true level falls 1 to 0) | upstream convention |")
    A("| Gradient clipping | none | `clip_grad_norm_(1.0)` | none (matches upstream) |")
    A("| Loss | L1 on noise, mean over batch x channels x pixels | same | same |")
    A("| Optimiser | Adam, lr 1e-4 | same | same |")
    A("| EMA | config field marked \"not used now\"; no code | none | none |")
    A("| Sampling weights | raw `state_dict` | raw `state_dict` | raw `state_dict` |")
    A("")
    A("The conditioning mismatch is the substantive difference. It is not a cosmetic detail: the "
      "denoiser is asked at sampling time for the noise at level sqrt(alpha_bar), and the first "
      "trainer never showed it that quantity.\n")
    A("## 2. Noise-prediction error (validation pairs)\n")
    if mse:
        A(f"Identical noisy inputs, {mse['n_pairs']} validation pairs, timesteps {mse['timesteps']}; "
          "only the value handed to the denoiser differs between the two columns.\n")
        A("| Checkpoint | MSE under upstream conditioning | MSE under `t/T` conditioning |")
        A("|---|---|---|")
        for k, v in mse["mean_mse"].items():
            A(f"| {k} | {v['upstream']:.5f} | {v['legacy']:.5f} |")
        A("")
        ev = mse["evidence"]
        A(f"- The first checkpoint is {f(ev['ours_upstream_over_legacy'], 1)}x worse under the "
          f"conditioning its sampler uses than under the one its trainer used.")
        A(f"- The released checkpoint shows the opposite pattern, "
          f"{f(ev['released_legacy_over_upstream'], 1)}x worse under `t/T`.")
        A(f"- The retrained checkpoint matches upstream "
          f"(prefers upstream = {mse.get('fixed_trainer_prefers_upstream')}).")
        A("")
        A("**Limitation of this test, stated plainly.** At high timesteps the noisy input is almost "
          "pure noise, so a model that simply copies its input scores well regardless of conditioning. "
          "The absolute MSE values are therefore not interpretable as model quality; only the "
          "*within-checkpoint comparison between the two conditioning values* is, because the input "
          "and the target are identical in both columns. The test is also not independent evidence of "
          "the bug: the bug was found by reading the code, and this test confirms its signature.\n")
    A("## 3. Retraining with the corrected trainer\n")
    if fixed_log:
        hist = fixed_log["history"]
        A(f"20,000 iterations, batch 4, lr 1e-4, no gradient clipping, {f(fixed_log['seconds'] / 60, 1)} "
          f"minutes on A100-40GB. Validation noise-prediction L1 fell from {f(hist[0]['val_l1'], 4)} at "
          f"iteration {hist[0]['iteration']:,} to {f(hist[-1]['val_l1'], 4)} at {hist[-1]['iteration']:,}.\n")
    if scores:
        A("Sampled quality on 50 validation pairs (1,000 steps, re-derived schedule, bf16):\n")
        A("| Condition | PSNR | SSIM | LPIPS | HF energy | HF vs hairy input | HF vs reference | Noise sigma | Sigma vs hairy input |")
        A("|---|---|---|---|---|---|---|---|---|")
        for r in scores["conditions"]:
            A(f"| {r['condition']} | {f(r['psnr'])} | {f(r['ssim'], 3)} | {f(r['lpips'], 3)} | "
              f"{f(r['hf_energy'], 4)} | {f(r['hf_ratio_vs_hairy'])}x | {f(r['hf_ratio_vs_reference'])}x | "
              f"{f(r['noise_sigma_mad'], 4)} | {f(r['sigma_ratio_vs_hairy'])}x |")
        ref = scores["references"]
        A(f"| hairy input (no model) | {f(ref['hairy_input']['psnr'])} | {f(ref['hairy_input']['ssim'], 3)} | "
          f"- | {f(ref['hairy_input']['hf_energy'], 4)} | 1.00x | "
          f"{f(ref['hairy_input']['hf_energy'] / ref['reference']['hf_energy'])}x | "
          f"{f(ref['hairy_input']['noise_sigma_mad'], 4)} | 1.00x |")
        A(f"| hairless reference | - | - | - | {f(ref['reference']['hf_energy'], 4)} | "
          f"{f(ref['reference']['hf_energy'] / ref['hairy_input']['hf_energy'])}x | 1.00x | "
          f"{f(ref['reference']['noise_sigma_mad'], 4)} | "
          f"{f(ref['reference']['noise_sigma_mad'] / ref['hairy_input']['noise_sigma_mad'])}x |")
        A("")
        tr = scores["checkpoint_trend"]
        A(f"**Trend across training:** PSNR {', '.join(f'{p:.2f}' for p in tr['psnr'])} at iterations "
          f"{', '.join(f'{i:,}' for i in tr['iterations'])}; total gain {f(tr['gain_db'])} dB, largest "
          f"successive drop {f(tr['max_successive_drop_db'])} dB. The pre-registered label is "
          f"**{tr['label']}**, so the \"monotonic improvement\" pattern that would have meant "
          f"\"undertrained\" is not present.")
        v = scores.get("fixed_arm_validity")
        if v:
            A(f"\n**Validity gate (D22):** PSNR {f(v['psnr'])} against a required {f(v['hairy_psnr'] + 3)} "
              f"(hairy input {f(v['hairy_psnr'])} + 3 dB); SSIM {f(v['ssim'], 3)} against hairy "
              f"{f(v['hairy_ssim'], 3)}. **Valid = {v['valid']}.**\n")
    A("## 4. Noise versus blur, measured against the hairy input\n")
    if scores:
        ref = scores["references"]
        A("The first diagnosis compared our output's high-frequency energy with the *hairless "
          "reference* and reported \"about 15x\". That comparison was misleading, because the hairy "
          "input itself already carries "
          f"{f(ref['hairy_input']['hf_energy'] / ref['reference']['hf_energy'])}x the reference's "
          "high-frequency energy. Measured against the hairy input, which is the honest baseline:\n")
        for r in scores["conditions"]:
            A(f"- **{r['condition']}:** HF energy {f(r['hf_ratio_vs_hairy'])}x the hairy input, noise "
              f"sigma {f(r['sigma_ratio_vs_hairy'])}x the hairy input.")
        A("")
        A("So the first checkpoint's output was **noisier than the hairy input it was given** "
          "(2.9x the high-frequency energy, 19.7x the noise sigma), which is the opposite of blur. The "
          "retrained checkpoint is quieter than the hairy input but still carries about 4x its noise "
          "sigma, and its PSNR is below the hairy input's, so it is not a usable restoration either. "
          "The word \"over-smoothed\" was wrong for both, and is withdrawn.\n")
    A("## 5. Warm start and overfit tests\n")
    if warm:
        A("| Trainer | Pre-fine-tune L1 | Mean L1, last 100 iterations | Ratio | Loss jump (>1.5x)? |")
        A("|---|---|---|---|---|")
        for mode in ("legacy", "upstream"):
            w = warm[mode]
            A(f"| {mode} | {f(w['pre_l1'], 4)} | {f(w['last100_mean_l1'], 4)} | {f(w['ratio'], 3)} | {w['loss_jump']} |")
        A("")
        A("Neither trainer shows a loss jump when fine-tuning the released weights, so this test did "
          "**not** discriminate between them. It is reported as inconclusive rather than as support "
          "for either branch. The reason is visible in the numbers: the released checkpoint is already "
          "at a low loss under both conditioning values, so 500 iterations of fine-tuning cannot "
          "produce a large enough jump to detect.\n")
    if over:
        A(f"**Overfit test:** 8 training pairs, {over['iterations']:,} iterations, then sampled at "
          f"{over['steps']} steps. Mean PSNR {f(over['mean_psnr'])} against a hairy-input baseline of "
          f"{f(over['hairy_psnr'])} (margin {f(over['margin_db'])} dB, required +3). "
          f"**Passed = {over['passed']}.**\n")
        A("This test is **not evidence about the trainer**, because it sampled with the re-derived "
          "short schedule that section 6 shows to be broken. It needs a rerun with the respaced "
          "sampler before it can be read either way.\n")
    A("## 6. The short sampler was also wrong\n")
    if sweep:
        A("Sampling at fewer steps re-derived a linear beta schedule over the shorter chain. Because "
          "the denoiser is conditioned on sqrt(alpha_bar), that chain ends at a final noise level far "
          "above the trained one. Measured on the released checkpoint, 50 validation pairs:\n")
        A("| Steps (re-derived) | PSNR | SSIM | LPIPS | s/image |")
        A("|---|---|---|---|---|")
        for r in sweep["rows"]:
            A(f"| {r['steps']} | {f(r['psnr'])} | {f(r['ssim'], 3)} | {f(r['lpips'], 3)} | {f(r['seconds_per_image'], 2)} |")
        A("")
    if resp:
        A("With a **respaced** sampler, which visits the same noise-level path at a subset of "
          "timesteps, the same checkpoints on the same 50 pairs:\n")
        A("| Checkpoint | Steps | PSNR | SSIM | LPIPS | s/image |")
        A("|---|---|---|---|---|---|")
        for name, blk in resp["checkpoints"].items():
            for r in blk["rows"]:
                A(f"| {name} | {r['steps']} | {f(r['psnr'])} | {f(r['ssim'], 3)} | {f(r['lpips'], 3)} | "
                  f"{f(r['seconds_per_image'], 2)} |")
        A("")
        A(f"Hairy-input floor on these pairs: PSNR {f(resp['hairy_floor']['psnr'])}, SSIM "
          f"{f(resp['hairy_floor']['ssim'], 3)}. The pre-registered choice rule (D24) picks "
          f"**{resp['checkpoints']['released']['choice'].get('chosen_steps')} steps** for the released "
          f"checkpoint and **{resp['checkpoints']['ours_fixed']['choice'].get('chosen_steps')}** for the "
          f"retrained one (no value passes the gate).\n")
    A("## 7. What this means for the study\n")
    A("1. **The first Arm C is a failed reproduction, not a test of DM-AHR.** It was trained with a "
      "conditioning bug and sampled with a mismatched schedule. It moves to an appendix and out of the "
      "confirmatory family.")
    A("2. **The corrected retrain is still not a valid DM-AHR arm.** It fails the pre-registered "
      "validity gate, so the confirmatory DM-AHR comparisons (A vs C-fixed, B vs C-fixed) are reported "
      "as **untested**, and the confirmatory Holm family keeps its pre-registered size of 3.")
    A("3. **The released checkpoint is a valid, exploratory DM-AHR arm.** It passes the gate at 25 "
      "respaced steps. It is labelled exploratory because its training data are undocumented and the "
      "paper states that HAM10000 images outside its 700-image test set were used for training, so it "
      "has very likely seen this study's clean validation and test images. No independence claim is "
      "made for it.")
    A("4. **H1 and H2 for DM-AHR are tested only through the exploratory arm.** Their verdicts are "
      "stated from that arm alone, with the independence caveat attached.")
    A("5. **The iteration framing is corrected.** The first Arm C was trained at 20,000 iterations, "
      "the paper's stated count, which is about 3% of the released checkpoint's 725,000. The paper's "
      "text and its own release disagree; that is a fact about the paper, not a budget excuse for this "
      "study. \"Under-resourced versus the paper\" is withdrawn.")
    A("")
    A("## 8. What is still open\n")
    A("- **Why the corrected retrain still fails is not established.** The conditioning bug is fixed "
      "and the noise-prediction error now matches upstream, yet sampled quality stays below the hairy "
      "input. Candidates not yet tested: the synthetic-hair pairs may be too few or too uniform for "
      "20,000 iterations; the L1-on-noise objective with a 64-channel UNet may need the paper's full "
      "schedule; the 128 px training resolution may be too low for the hair structures. Distinguishing "
      "these needs another retrain, which the remaining budget does not cover.")
    A("- **The overfit test must be rerun with the respaced sampler** before it can be read.")
    A("- **The warm-start test did not discriminate** and is reported as inconclusive.")
    A("- **The paper's own hairy-input floor is not reported**, so the paper's 41.04 dB cannot be "
      "placed against a no-model baseline. See `reports/paper_reproduction.md`.")
    A("")
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
